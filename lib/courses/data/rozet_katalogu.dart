  const Rozet(this.simge,
      {required this.tr, required this.en, required this.de, required this.es});

  final String simge;
  final String tr;
  final String en;
  final String de;
  final String es;

  String adi(String lang) => AppLang.pick(lang, tr: tr, en: en, de: de, es: es);
}

