/// Kutlama penceresi rozet adini ve simgesini kendi icindeki iki kucuk
/// tablodan okuyordu; tabloda yalnizca alti Scratch rozeti vardi. Geri
/// kalan butun rozetler (Scratch'in 14'u, mBlock'un tamami, diger
/// kurslar) "Rozet" / 🏆 diye cikiyordu. `ScratchBadges.all` adinda ikinci
/// bir liste de vardi; hic kullanilmiyordu ve `scratch_starter` icin
/// baska bir simge yaziyordu.
///
/// Artik ders verisindeki her `badge:` kimligi burada. Adlar dersin
/// ozet adimindaki "... rozetini kazandin" cumlesiyle ayni; test
/// (`rozet_katalogu_test.dart`) her kimligin burada dort dilde
/// bulundugunu ve rozet vaat eden her ozetin bir rozeti oldugunu sinar.
